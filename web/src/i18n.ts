export function t(source: string, values: Record<string, string | number> = {}) {
  const template = currentLanguage.value === "de" ? (de[source] ?? source) : source;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

export function formatDate(value: string | Date) {
  return new Date(value).toLocaleString(currentLanguage.value === "de" ? "de-DE" : "en-GB");
}

export function setSiteLanguage(language: UiLanguage) {
  siteLanguage.value = language;
  document.documentElement.lang = currentLanguage.value;
}

export function setDocumentLanguage(language: unknown) {
  documentLanguage.value = language === "de" || language === "en" ? language : null;
  document.documentElement.lang = currentLanguage.value;
}

export function selectLanguage(language: UiLanguage) {
  selectedLanguage.value = language;
  document.documentElement.lang = language;
}

export function resetDocumentLanguage() {
  documentLanguage.value = null;
  selectedLanguage.value = null;
  document.documentElement.lang = currentLanguage.value;
}
